fn main() {
    // Начиная с Android 15 часть устройств (в том числе новые Samsung)
    // использует страницы памяти по 16 КБ вместо 4 КБ — нативные библиотеки
    // должны быть выровнены под это при компоновке, иначе система
    // предупреждает/может отказаться эффективно загрузить `.so`.
    //
    // Не через RUSTFLAGS/.cargo/config.toml — Tauri сам жёстко выставляет
    // `CARGO_TARGET_<ARCH>_RUSTFLAGS` при сборке под Android, и любой наш
    // RUSTFLAGS был бы просто перекрыт целиком (переменные окружения не
    // складываются с `target.*.rustflags` в конфиге — используется только
    // одна, более специфичная). А `cargo:rustc-link-arg` из build.rs
    // добавляется линковщику всегда, независимо от RUSTFLAGS.
    //
    // ВАЖНО: `#[cfg(target_os = "android")]` здесь был бы неверен — build.rs
    // компилируется и запускается для ХОСТА (Windows), а не для целевой
    // платформы кросс-компиляции. Нужно читать `CARGO_CFG_TARGET_OS`,
    // которую Cargo выставляет специально для этого случая.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("android") {
        println!("cargo:rustc-link-arg=-Wl,-z,max-page-size=16384");
    }

    tauri_build::build()
}
